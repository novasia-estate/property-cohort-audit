library(propertycohorts)
data <- synthetic_cohorts()
result <- audit_cohorts(data$before, data$after, c("district", "property_type"))
stopifnot(result$summary$raw_change == 1200, result$summary$within_change == 0)
destination <- Sys.getenv("COHORT_REPORT_DIR", "example-report")
write_cohort_report(result, destination)
grDevices::pdf(file.path(destination, "decomposition.pdf"), width = 8, height = 5)
plot(result)
grDevices::dev.off()
print(result)
